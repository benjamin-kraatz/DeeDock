import Foundation

/// Human-readable names. The notes say what each interval includes so a reader can't overread a number.
enum MetricLabel {
    static let order: [String] = ["launch", "hoverResponse", "dockReveal", "dockRevealOverDelay",
                                  "launcherOpenFromClick", "launcherOpen", "launcherQuery", "launcherRank",
                                  "magnifyUpdate", "stackOpen", "peekOpen", "windowSearchOpen"]

    static func title(_ key: String) -> String {
        switch key {
        case "launch": "Launch to first dock frame"
        case "hoverResponse": "Pointer over dock → magnified frame"
        case "dockReveal": "Activation zone → dock on screen"
        case "dockRevealOverDelay": "Dock reveal beyond the configured delay"
        case "launcherOpenFromClick": "Click → Launcher's first frame"
        case "launcherOpen": "Launcher request → first frame"
        case "launcherQuery": "Keystroke → Launcher results"
        case "launcherRank": "Launcher ranking"
        case "magnifyUpdate": "Magnification update"
        case "stackOpen": "Folder stack opens"
        case "peekOpen": "Window Peek opens"
        case "windowSearchOpen": "Window search opens"
        default: key
        }
    }

    static func note(_ key: String) -> String {
        switch key {
        case "launch": "Process start (kernel) to the first dock panel committed. Warm launches."
        case "hoverResponse", "dockReveal", "launcherOpenFromClick":
            "Real input posted through the HID event tap; timed from the event's hardware timestamp."
        case "dockRevealOverDelay": "Reveal minus the configured reveal delay."
        case "launcherQuery": "Includes the search's deliberate 120 ms debounce."
        case "launcherRank": "Ranking work only: apps, windows, capsules, Shelf, Shortcuts, modes."
        case "magnifyUpdate": "In-process pointer sweep; no event delivery."
        case "peekOpen": "Panel on screen; thumbnails stream in afterwards."
        default: key.hasPrefix("launcherSearch") ? "Synthetic 10,000-app index, compiled with -O." : ""
        }
    }
}

enum Markdown {
    static func results(_ summary: RunSummary) -> String {
        var lines = [
            "# DDock benchmark results", "",
            "Generated by `benchmarks/run.sh` on \(summary.date) at commit `\(summary.commit)`.",
            "Measured on a single machine. Treat the numbers as indicative for that hardware, not as guarantees.", "",
            "![Benchmark summary](results/latest.svg)", "",
            "## Machine", "",
            "| | |", "|---|---|",
        ]
        for key in ["model", "chip", "memory", "os", "displays", "power", "lowPowerMode", "thermalState"] {
            lines.append("| \(key) | \(summary.machine[key] ?? "–") |")
        }
        let context = summary.context.sorted { $0.key < $1.key }.map { "`\($0.key)=\($0.value)`" }
        lines += ["", "DDock configuration: " + context.joined(separator: ", "), ""]

        if let ddock = summary.resources["ddock"] {
            let dock = summary.resources["dock"]
            lines += ["## Idle cost", "",
                      "Both processes sampled once per second over the same \(Int(ddock.seconds)) s window, with the Mac otherwise idle.", "",
                      "| | DDock | macOS Dock |", "|---|---:|---:|",
                      "| Memory (Activity Monitor footprint, median) | \(mib(ddock)) | \(dock.map(mib) ?? "–") |",
                      "| CPU (% of one core) | \(Format.number(ddock.cpuPercent)) % | \(dock.map { Format.number($0.cpuPercent) + " %" } ?? "–") |",
                      "| Wakeups per second | \(Format.number(ddock.wakeupsPerSecond)) | \(dock.map { Format.number($0.wakeupsPerSecond) } ?? "–") |",
                      "| Average power | \(power(ddock)) | \(dock.map(power) ?? "–") |", ""]
        }
        if let active = summary.resources["ddockScenarios"], let peak = active.footprintMiB {
            lines += ["While scenarios ran, DDock's footprint peaked at \(Format.number(peak.max)) MiB.", ""]
        }

        let keys = MetricLabel.order.filter { summary.metrics[$0] != nil }
            + summary.metrics.keys.filter { !MetricLabel.order.contains($0) }.sorted()
        if !keys.isEmpty {
            lines += ["## Response times (ms)", "",
                      "Nearest-rank percentiles of raw samples. With several runs, the run with the median p50 is shown and the p50 range gives the spread.", "",
                      "| Interaction | p50 | p90 | p95 | p99 | max | n | p50 range | Notes |",
                      "|---|---:|---:|---:|---:|---:|---:|---:|---|"]
            for key in keys {
                guard let metric = summary.metrics[key] else { continue }
                let d = metric.distribution
                let range = metric.p50Range.map { "\(Format.number($0[0]))–\(Format.number($0[1]))" } ?? "–"
                lines.append("| \(MetricLabel.title(key)) | \(Format.number(d.p50)) | \(Format.number(d.p90)) | \(Format.number(d.p95)) | \(Format.number(d.p99)) | \(Format.number(d.max)) | \(d.count) | \(range) | \(MetricLabel.note(key)) |")
            }
            lines.append("")
        }

        if !summary.frames.isEmpty {
            lines += ["## Frame pacing", "",
                      "Display-link callbacks on the main thread. A hitch is a callback more than 1.5 frames late.", "",
                      "| Scenario | Frames | Hitches | Hitch ratio (ms/s) | Frame p95 (ms) |", "|---|---:|---:|---:|---:|"]
            for (name, frames) in summary.frames.sorted(by: { $0.key < $1.key }) {
                lines.append("| \(name) | \(frames.frames) | \(frames.hitches) | \(Format.number(frames.hitchRatio)) | \(frames.intervals.map { Format.number($0.p95) } ?? "–") |")
            }
            lines.append("")
        }

        if !summary.budgets.isEmpty {
            lines += ["## Budgets", "", "| Budget | Value | Limit | |", "|---|---:|---:|---|"]
            for budget in summary.budgets {
                let state = budget.passed.map { $0 ? "pass" : "**over**" } ?? "not measured"
                lines.append("| \(budget.label) | \(budget.value.map(Format.number) ?? "–") | \(Format.number(budget.limit)) | \(state) |")
            }
            lines.append("")
        }
        if !summary.skipped.isEmpty {
            lines += ["## Not measured", ""]
            lines += summary.skipped.sorted { $0.key < $1.key }.map { "- `\($0.key)`: \($0.value)" }
            lines.append("")
        }
        lines += ["## Method", "",
                  "See [benchmarks/README.md](README.md) for what each stage does and how to reproduce these numbers.", ""]
        return lines.joined(separator: "\n")
    }

    private static func mib(_ usage: ProcessResourceSummary) -> String {
        usage.footprintMiB.map { Format.number($0.p50) + " MiB" } ?? "–"
    }

    private static func power(_ usage: ProcessResourceSummary) -> String {
        usage.energyMilliwatts.map { Format.number($0) + " mW" } ?? "–"
    }
}
